const TEMP_FOLDER_NAME: &str = "temp_spectra";
const TEST_FILE_NAME: &str = "test_files/test2.mgf";

pub struct ClusterManager<B: Backend> {
    cpu_spectral_buffer: Vec<f32>,
    spectral_buffer: Tensor<B, 2>,
    similarity_matrix_buffer: Tensor<B, 2>,
    precursor_mz: Vec<f32>,
    current_index: usize,
    indices: Vec<usize>,
    hash_config: HashedSpectrumConfig,
}

impl<B: Backend> ClusterManager<B> {
    pub fn new(hash_size: usize, number_of_spectra: Option<usize>, device: &B::Device) -> Self {
        let number_of_spectra = number_of_spectra.unwrap_or(64);
        let spectral_shape = [number_of_spectra, hash_size];
        let sim_matrix_shape = [number_of_spectra, number_of_spectra];
        ClusterManager {
            cpu_spectral_buffer: vec![0.0; number_of_spectra * hash_size],
            spectral_buffer: Tensor::zeros(spectral_shape, device),
            similarity_matrix_buffer: Tensor::zeros(sim_matrix_shape, device),
            precursor_mz: vec![0.0; number_of_spectra],
            indices: vec![0; number_of_spectra],
            current_index: 0,
            hash_config: HashedSpectrumConfig::default().hash_size(hash_size),
        }
    }
    fn hash_size(&self) -> usize {
        self.hash_config.hash_size
    }

    pub fn split_on_mz(
        &mut self,
        mz_tolerance: MassTolerance,
        spectra: &mut [MSNSpectrum],
    ) -> Result<(), std::io::Error> {
        // 1. Sort spectra
        spectra.sort_by(|spectrum1, spectrum2| {
            spectrum1
                .precursor_mz
                .partial_cmp(&spectrum2.precursor_mz)
                .unwrap_or(std::cmp::Ordering::Equal)
        });

        let mut last_mass = 0.0;
        let mut splits = Vec::new();

        // 2. Calculate splits using the Enum
        for (index, spectrum) in spectra.iter().enumerate() {
            let gap = spectrum.precursor_mz - last_mass;

            let exceeds_tolerance = match mz_tolerance {
                MassTolerance::Da(tol) => gap > tol,
                MassTolerance::Ppm(tol) => {
                    // For the very first element (index 0), last_mass is 0.0.
                    // We must force a split here to start the first bucket.
                    if last_mass == 0.0 {
                        true
                    } else {
                        // The allowed gap scales with the mass for ppm
                        let allowed_gap = last_mass * (tol / 1_000_000.0);
                        gap > allowed_gap
                    }
                }
            };

            if exceeds_tolerance {
                splits.push(index);
            }
            last_mass = spectrum.precursor_mz;
        }

        // Ensure the last boundary is the end of the array
        if let Some(&last_split) = splits.last() {
            if last_split != spectra.len() {
                splits.push(spectra.len());
            }
        } else {
            // Failsafe: if spectra was empty, just return early
            return Ok(());
        }

        // Create folder to store spectra
        ensure_empty_dir(TEMP_FOLDER_NAME)?;
        // --- THE NEW DUMPING LOGIC ---
        // Pre-allocate the vector since we know exactly how many batches we have
        let mut all_batches = Vec::with_capacity(splits.len().saturating_sub(1));

        for window in splits.windows(2) {
            let start = window[0];
            let end = window[1];

            all_batches.push(MassSpectrumBatch {
                batch: spectra[start..end].to_vec(),
            });
        }

        // Wrap them in the collection and write to a single file
        let collection = MassSpectrumBatchCollection { batch: all_batches };
        collection.dump(&format!("{TEMP_FOLDER_NAME}/all_batches.bin"))?;

        Ok(())
    }
    pub fn batch_process(&mut self) -> Result<(), std::io::Error> {
        // 1. Read the single file containing all batches into memory
        let file_path = format!("{TEMP_FOLDER_NAME}/all_batches.bin");
        let mut file = File::open(file_path)?;

        // We use a completely empty Vec and let read_to_end grow it dynamically,
        // or you could check file metadata for exact size to pre-allocate.
        let mut buffer = Vec::new();
        file.read_to_end(&mut buffer)?;

        // Access the overarching collection
        let collection =
            rkyv::access::<ArchivedMassSpectrumBatchCollection, Error>(&buffer).unwrap();

        let hash_size = self.hash_size();
        // 2. Iterate over the batches inside the collection
        for batch in collection.batch.iter() {
            // Because batch.batch is an ArchivedVec, we use `.as_slice()` to easily get
            // the length and parallel iterators without moving out of the archive.
            let archived_spectra = batch.batch.as_slice();
            let number_of_spectra = archived_spectra.len();

            self.cpu_spectral_buffer
                .resize(archived_spectra.len() * self.hash_size(), 0.0);
            self.cpu_spectral_buffer.fill(0.0);

            // 2. Zip the mutable chunks with the batch items in parallel
            self.cpu_spectral_buffer
                .par_chunks_exact_mut(hash_size)
                .zip(archived_spectra.par_iter())
                .for_each(|(buffer_slice, spectrum)| {
                    spectrum
                        .spectrum
                        .hash_into_buffer(&self.hash_config, buffer_slice);
                });

            let shape = [number_of_spectra, hash_size];
            self.spectral_buffer =
                Tensor::from(TensorData::new(self.cpu_spectral_buffer.clone(), shape));

            // normalize_spectra_in_place(&mut self.spectral_buffer, hash_size);

            self.l2_normalize();
            self.compute_similarity_matrix();

            let clusters = dbscan(
                &self
                    .similarity_matrix_buffer
                    .clone()
                    .into_data()
                    .to_vec::<f32>()
                    .unwrap(),
                batch.batch.len(),
                EPSILON_CUTOFF,
                MIN_NEIGHBORS,
            );

            if clusters.iter().any(|point| *point != ClusterLabel::Noise) {
                println!("Clusters found");
            }
        }
        Ok(())
    }
    fn compute_similarity_matrix(&mut self) {
        let number_of_spectra = self.spectral_buffer.dims()[0];
        if number_of_spectra < 2 {
            return; // Nothing to compare
        }

        let a_t = self.spectral_buffer.clone().transpose();
        self.similarity_matrix_buffer = self.spectral_buffer.clone().matmul(a_t);
    }

    fn l2_normalize(&mut self) {
        // 1. powf_scalar and sum_dim consume the tensor, so we pass a cheap clone.
        let sum_of_squares = self.spectral_buffer.clone().powf_scalar(2.0).sum_dim(1);

        // 2. Chain the math operations cleanly
        let l2_norm_safe = sum_of_squares.sqrt().add_scalar(1e-8);

        // 3. Divide to normalize. Again, we pass a cheap clone of the buffer
        // because the division operator consumes the left operand.
        self.spectral_buffer = self.spectral_buffer.clone() / l2_norm_safe;
    }
}

