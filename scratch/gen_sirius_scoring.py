def emit_map(name, doc, m):
    print(f"/// {doc}")
    print(f"pub(crate) static {name}: &[(&str, f64)] = &[")
    for k in sorted(m):
        print(f'    ("{k}", {float(m[k]):.10}),')
    print("];\n")


def emit_set(name, doc, s):
    print(f"/// {doc}")
    print(f"pub(crate) static {name}: &[&str] = &[")
    for k in sorted(set(s)):
        print(f'    "{k}",')
    print("];\n")


def main():
    d = json.load(open(PROFILE))
    fpa = d["FragmentationPatternAnalysis"]
    loss_scorers = {s["$name"].split(".")[-1]: s for s in fpa["lossScorers"]}
    decomp = {s["$name"].split(".")[-1]: s for s in fpa["decompositionScorers"]}

    print(HEADER, end="")

    cl = loss_scorers["CommonLossEdgeScorer"]
    print(f"/// CommonLossEdgeScorer normalization (subtracted from every listed-loss score).")
    print(f"pub(crate) const COMMON_LOSS_NORMALIZATION: f64 = {float(cl['normalization']):.6};")
    rec = cl.get("recombinator", {})
    print(f"/// MinimalScoreRecombinator penalty for a 2-step recombined loss.")
    print(f"pub(crate) const RECOMBINATOR_PENALTY: f64 = {float(rec.get('penalty', -1)):.6};\n")
    # split the implausible (large negative) entries out
    impl = {k: v for k, v in cl["losses"].items() if v <= -4.0}
    common = {k: v for k, v in cl["losses"].items() if v > -4.0}
    emit_map("COMMON_LOSSES", "Loss formula -> SIRIUS common-loss score (pre-normalization).", common)
    emit_set("IMPLAUSIBLE_LOSSES", "Losses SIRIUS scores at ln(0.01) regardless of size.", impl.keys())

    # ── MinimalScoreRecombinator (CommonLossEdgeScorer.getRecombinatedList) ──
    # For every unordered pair (a, b) of non-negative common losses, if
    # explaining the combined loss a+b as "two common losses, one step" beats its
    # direct score, store it. Faithful to MinimalScoreRecombinator.recombinate:
    #   aScore = lossSize(a) + source[a];  bScore = lossSize(b) + source[b]
    #   recombinationScore = min(aScore, bScore) + penalty        (penalty = -1)
    #   combinationScore   = lossSize(a+b) + source.get(a+b, 0)
    #   if recombinationScore > combinationScore:
    #       store[a+b] = recombinationScore - lossSize(a+b)
    lsd = [s for s in fpa["peakPairScorers"] if s["$name"].endswith("LossSizeScorer")][0]
    ls_mean = float(lsd["distribution"]["mean"])
    ls_var = float(lsd["distribution"]["variance"])
    ls_norm = float(lsd["normalization"])
    penalty = float(rec.get("penalty", -1.0))
    import math as _m
    _MASS = {  # exact monoisotopic masses, enough for the loss dictionary
        "C": 12.0, "H": 1.007825032, "N": 14.003074005, "O": 15.994914620,
        "P": 30.973761998, "S": 31.972071174, "F": 18.998403163,
        "Cl": 34.968852682, "Br": 78.9183376, "I": 126.904473,
        "Na": 22.989769282, "K": 38.963706487,
    }
    _tok = re.compile(r"([A-Z][a-z]?)(\d*)")
    def _parse(f):
        d = {}
        for el, n in _tok.findall(f):
            if el:
                d[el] = d.get(el, 0) + (int(n) if n else 1)
        return d
    def _mass(d):
        return sum(_MASS[e] * c for e, c in d.items())
    def _hill(d):
        parts = []
        for e in ["C", "H"]:
            if d.get(e):
                parts.append(e + (str(d[e]) if d[e] > 1 else ""))
        for e in sorted(k for k in d if k not in ("C", "H")):
            if d[e]:
                parts.append(e + (str(d[e]) if d[e] > 1 else ""))
        return "".join(parts)
    def _loss_size(mass):
        if mass <= 0:
            return _m.log(1e-12) - ls_norm
        sd = _m.sqrt(ls_var)
        z = (_m.log(mass) - ls_mean) / sd
        dens = _m.exp(-0.5 * z * z) / (mass * sd * _m.sqrt(2 * _m.pi))
        return _m.log(max(1e-12, dens)) - ls_norm

    src = {k: v for k, v in cl["losses"].items() if v >= 0.0}
    src_parsed = {k: _parse(k) for k in src}
    recomb = {}
    keys = list(src)
    for i, a in enumerate(keys):
        da = src_parsed[a]
        a_score = _loss_size(_mass(da)) + src[a]
        for b in keys[i:]:
            db = src_parsed[b]
            b_score = _loss_size(_mass(db)) + src[b]
            comb = {e: da.get(e, 0) + db.get(e, 0) for e in set(da) | set(db)}
            comb_mass = _mass(comb)
            comb_key = _hill(comb)
            comb_direct = cl["losses"].get(comb_key, 0.0)
            combination_score = _loss_size(comb_mass) + comb_direct
            recombination_score = min(a_score, b_score) + penalty
            if recombination_score > combination_score:
                final_score = recombination_score - _loss_size(comb_mass)
                # keep the best when several pairs hit the same combination
                if comb_key not in recomb or final_score > recomb[comb_key]:
                    recomb[comb_key] = final_score
    emit_map(
        "COMMON_LOSS_RECOMBINED",
        "MinimalScoreRecombinator output: 2-common-loss combination -> stored score.",
        recomb,
    )

    fr = loss_scorers["FreeRadicalEdgeScorer"]
    print(f"/// FreeRadicalEdgeScorer: penalty for any radical (odd-electron) loss...")
    print(f"pub(crate) const RADICAL_LOSS_PENALTY: f64 = {float(fr['radicalPenalty']):.10};")
    print(f"/// ...and the smaller penalty for a loss on the known-radical whitelist.")
    print(f"pub(crate) const KNOWN_RADICAL_LOSS: f64 = {float(next(iter(fr['commonRadicals'].values()))):.10};")
    print(f"pub(crate) const FREE_RADICAL_NORMALIZATION: f64 = {float(fr['normalization']):.10};\n")
    emit_set("KNOWN_RADICALS", "Loss formulas that are 'expected' radicals (halogens, alkyls, ...).", fr["commonRadicals"].keys())

    sel = loss_scorers["StrangeElementLossScorer"]
    print(f"pub(crate) const STRANGE_ELEMENT_LOSS_BONUS: f64 = {float(sel['score']):.10};\n")
    emit_set("STRANGE_ELEMENT_LOSSES", "Losses SIRIUS gives a bonus for (organo-S/Cl/Br/P/I).", sel["losses"])

    dbe = loss_scorers["DBELossScorer"]
    print(f"pub(crate) const DBE_LOSS_SCORE: f64 = {float(dbe['score']):.10};\n")
    pcn = loss_scorers["PureCarbonNitrogenLossScorer"]
    print(f"pub(crate) const PURE_CN_LOSS_PENALTY: f64 = {float(pcn['penalty']):.10};\n")

    ls = [s for s in fpa["peakPairScorers"] if s["$name"].endswith("LossSizeScorer")][0]
    dist = ls["distribution"]
    print(f"pub(crate) const LOSS_SIZE_MEAN: f64 = {float(dist['mean']):.13};")
    print(f"pub(crate) const LOSS_SIZE_VARIANCE: f64 = {float(dist['variance']):.13};")
    print(f"pub(crate) const LOSS_SIZE_NORMALIZATION: f64 = {float(ls['normalization']):.13};\n")

    cf = decomp["CommonFragmentsScore"]
    print(f"pub(crate) const COMMON_FRAGMENT_NORMALIZATION: f64 = {float(cf['normalization']):.10};\n")
    emit_map("COMMON_FRAGMENTS", "Fragment formula -> SIRIUS common-fragment score (pre-normalization).", cf["fragments"])

    sfs = decomp["StrangeElementFragmentScorer"]
    print(f"pub(crate) const STRANGE_FRAGMENT_BONUS: f64 = {float(sfs['score']):.10};")
    print(f"pub(crate) const STRANGE_FRAGMENT_PENALTY: f64 = {float(sfs['penalty']):.10};")
    print(f"pub(crate) const STRANGE_FRAGMENT_MIN_MASS: f64 = {float(sfs['minMass']):.1};\n")
    emit_set("STRANGE_FRAGMENT_WHITELIST", "Non-CHNO fragments SIRIUS does not penalise above minMass.", sfs["whiteset"])

    ssf = decomp["StrangeElementSmallFragmentScorer"]
    print(f"pub(crate) const SMALL_STRANGE_FRAGMENT_BONUS: f64 = {float(ssf['score']):.6};")
    print(f"pub(crate) const SMALL_STRANGE_FRAGMENT_MAX_MASS: f64 = {float(ssf['maximalMass']):.1};\n")

    frag = {s["$name"].split(".")[-1]: s for s in fpa["fragmentScorers"]}
    crl = frag.get("CommonRootLossScorer")
    if crl is not None:
        print(f"/// CommonRootLossScorer normalization (subtracted from every listed root-loss bonus).")
        print(f"pub(crate) const COMMON_ROOT_LOSS_NORMALIZATION: f64 = {float(crl.get('normalization', 0.0)):.10};\n")
        emit_map(
            "COMMON_ROOT_LOSSES",
            "Cumulative precursor->fragment loss formula -> SIRIUS root-loss bonus.",
            crl["rootLosses"],
        )

    root = {s["$name"].split(".")[-1]: s for s in fpa["rootScorers"]}
    ser = root["StrangeElementRootScorer"]
    print(f"pub(crate) const STRANGE_ROOT_PENALTY: f64 = {float(ser['penalty']):.10};")
    ics = root.get("IntrinsicallyChargedScorer", {"score": -4.605170185988091})
    print(f"pub(crate) const INTRINSICALLY_CHARGED_SCORE: f64 = {float(ics['score']):.10};\n")


if __name__ == "__main__":
    main()
